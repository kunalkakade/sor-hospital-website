const DEFAULT_LANG = "mr";

function applyLang(lang) {
  const dict = I18N[lang] || I18N[DEFAULT_LANG];

  document.documentElement.lang = dict["html.lang"];
  document.documentElement.setAttribute("data-lang", lang);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const v = dict[el.getAttribute("data-i18n")];
    if (v != null) el.textContent = v;
  });
  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const v = dict[el.getAttribute("data-i18n-html")];
    if (v != null) el.innerHTML = v;
  });
  document.querySelectorAll("[data-i18n-ph]").forEach((el) => {
    const v = dict[el.getAttribute("data-i18n-ph")];
    if (v != null) el.setAttribute("placeholder", v);
  });
  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const v = dict[el.getAttribute("data-i18n-aria")];
    if (v != null) el.setAttribute("aria-label", v);
  });

  try { localStorage.setItem("lang", lang); } catch (e) {}

  // notify other widgets (e.g. Google reviews) that language changed
  try { window.dispatchEvent(new CustomEvent("langchange", { detail: lang })); } catch (e) {}
}

function initLang() {
  let lang = DEFAULT_LANG;
  try {
    const saved = localStorage.getItem("lang");
    if (saved && I18N[saved]) lang = saved;
  } catch (e) {}
  applyLang(lang);

  const btn = document.getElementById("langToggle");
  if (btn) {
    btn.addEventListener("click", () => {
      const next = (document.documentElement.getAttribute("data-lang") === "mr") ? "en" : "mr";
      applyLang(next);
    });
  }
}

// Apply ASAP to avoid English flash, then wire toggle on DOM ready.
if (document.readyState === "loading") {
  document.addEventListener("DOMContentLoaded", initLang);
} else {
  initLang();
}
